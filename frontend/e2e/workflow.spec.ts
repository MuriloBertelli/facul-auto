test('export preserves local work in a portable JSON file', async ({ page }) => {
  await page.goto('/')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar organização' }).click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toBe('campusflow-trabalhos.json')
  const stream = await download.createReadStream()
  if (!stream) throw new Error('Export file unavailable')
  const chunks: Buffer[] = []
  for await (const chunk of stream) chunks.push(Buffer.from(chunk))
  const data = JSON.parse(Buffer.concat(chunks).toString('utf8'))
  expect(data.assignments).toHaveLength(3)
  expect(data.assignments[0].title).toBe('Portfólio de desenvolvimento web')
  expect(data.exported_at).toBeTruthy()
})

test('mobile workflow stays within the screen and handles corrupt local data', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(() => localStorage.setItem('facul-auto.assignments.v1', '{invalid'))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Meus trabalhos' })).toBeVisible()
  await expect(page.getByText('Dados locais preservados para recuperação.')).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('facul-auto.assignments.v1'))).toBe('{invalid')
  const fits = await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)
  expect(fits).toBe(true)
  await page.getByRole('button', { name: 'Novo trabalho', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Novo trabalho', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Título do trabalho').fill('Trabalho somente nesta sessão')
  await page.getByRole('dialog').getByLabel('Disciplina', { exact: true }).fill('Projeto')
  await page.getByRole('dialog').getByRole('button', { name: 'Salvar trabalho', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Trabalho somente nesta sessão', exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('facul-auto.assignments.v1'))).toBe('{invalid')
  await page.reload()
  await expect(page.getByText('Dados locais preservados para recuperação.')).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('facul-auto.assignments.v1'))).toBe('{invalid')
})
