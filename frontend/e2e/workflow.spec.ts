import { test, expect } from '@playwright/test'

test('API routing serves JSON and refuses anonymous Canvas access', async ({ request }) => {
  const health = await request.get('/api/health')
  expect(health.status()).toBe(200)
  expect(health.headers()['content-type']).toContain('application/json')
  expect(await health.json()).toMatchObject({ status: 'ok', submissionsEnabled: false })
  const canvas = await request.get('/api/canvas/courses')
  expect(canvas.status()).toBe(401)
  expect(await canvas.json()).toHaveProperty('error')
})

test('create, edit, reload, filter and remove a local assignment', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Seu ambiente está em modo local.')).toBeVisible()
  await page.getByRole('button', { name: 'Novo trabalho', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Novo trabalho' })
  await dialog.getByLabel('Título do trabalho').fill('Entrega de teste do organizador')
  await dialog.getByLabel('Disciplina', { exact: true }).fill('Interfaces Web')
  await dialog.getByRole('combobox', { name: /^Status/ }).selectOption('ready')
  await dialog.getByLabel('Link do projeto publicado').fill('https://example.netlify.app/projeto')
  await dialog.getByLabel('Anotações').fill('Conferir navegação e responsividade.')
  await dialog.getByRole('button', { name: 'Salvar trabalho', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Prontos', exact: true }).click()
  await page.getByRole('button', { name: 'Entrega de teste do organizador', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Editar trabalho' })
  await expect(edit.getByLabel('Anotações')).toHaveValue('Conferir navegação e responsividade.')
  await edit.getByLabel('Título do trabalho').fill('Entrega revisada')
  await edit.getByRole('button', { name: 'Salvar trabalho', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Entrega revisada', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Entrega revisada', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Entrega revisada', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Entrega revisada', exact: true })).toHaveCount(0)
})

